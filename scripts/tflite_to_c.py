#!/usr/bin/env python3
"""Convert an INT8 LiteRT/TFLite model to static C source files (bare-metal B0 baseline).

Emits three files into src/software/model/:
  model_weights.c   all constant tensors (weights, biases) as C arrays
  model_params.h    extern decls, tensor shapes, zero-points (no floats)
  model_runner.c    ordered kernel-call sequence (ISA-independent C)

The generated C compiles on any target.
It is the B0 baseline.

W8A8: weights are INT8 per-channel symmetric, activations are INT8 asymmetric.

Run scripts/inspect_tflite.py first (done automatically via `make model_gen`) to
verify the op inventory.  Op names and kernel function names are derived entirely
from the loaded model — no hardcoded op list exists in this file.

Usage:
    python scripts/tflite_to_c.py --model <path/to/model.tflite>
"""

import argparse
import math
from pathlib import Path

import numpy as np

DEFAULT_OUT = "src/software/model"
BANNER      = "/* AUTO-GENERATED by scripts/tflite_to_c.py — DO NOT EDIT */\n"

def _op_to_kernel(op_name: str) -> str:
    """Derive the C kernel function name from a TFLite op name.

    Convention: kernel_<op_name_lower>_s8
      CONV_2D         →  kernel_conv_2d_s8
      FULLY_CONNECTED →  kernel_fully_connected_s8
      AVERAGE_POOL_2D →  kernel_average_pool_2d_s8
    """
    return "kernel_" + op_name.lower() + "_s8"

# ---------------------------------------------------------------------------
# Load
# ---------------------------------------------------------------------------

def _load(model_path: str):
    try:
        from ai_edge_litert.interpreter import Interpreter
    except ImportError:
        from tensorflow.lite import Interpreter  # type: ignore
    print(f"[info] loading {model_path}")
    interp = Interpreter(model_path=model_path)
    interp.allocate_tensors()
    return interp


# ---------------------------------------------------------------------------
# Graph analysis helpers
# ---------------------------------------------------------------------------

def _constant_set(interp) -> set[int]:
    """Indices of tensors baked into the flatbuffer (weights, biases).

    A tensor is constant iff it is never produced by any op and is not a
    model-level input.
    """
    ops          = interp._get_ops_details()  # noqa: SLF001
    op_outputs   = {idx for op in ops for idx in op["outputs"] if idx >= 0}
    model_inputs = {d["index"] for d in interp.get_input_details()}
    all_tensors  = {t["index"] for t in interp.get_tensor_details()}
    return all_tensors - op_outputs - model_inputs


def _reshape_aliases(interp) -> dict[int, int]:
    """Map RESHAPE output tensor index → its input tensor index.

    Lets the runner reuse the same buffer instead of copying.
    """
    alias: dict[int, int] = {}
    for op in interp._get_ops_details():  # noqa: SLF001
        if op["op_name"] != "RESHAPE":
            continue
        ins  = [i for i in op["inputs"]  if i >= 0]
        outs = [i for i in op["outputs"] if i >= 0]
        if ins and outs:
            alias[outs[0]] = ins[0]
    return alias


def _resolve(idx: int, aliases: dict[int, int]) -> int:
    """Follow RESHAPE alias chain to the canonical buffer index."""
    seen: set[int] = set()
    while idx in aliases and idx not in seen:
        seen.add(idx)
        idx = aliases[idx]
    return idx


# ---------------------------------------------------------------------------
# C formatting helpers
# ---------------------------------------------------------------------------

def _nelems(shape) -> int:
    n = 1
    for s in shape:
        n *= max(int(s), 0)
    return n


def _ctype(dtype) -> str:
    name = np.dtype(dtype).name
    if name == "float32":
        raise TypeError(
            f"tensor dtype float32 is not allowed in a W8A8 model — "
            "ensure the .tflite was fully quantized before running this script."
        )
    return {
        "int8":  "int8_t",
        "uint8": "uint8_t",
        "int16": "int16_t",
        "int32": "int32_t",
    }.get(name, "uint8_t")


def _write_c_array(f, ctype: str, name: str, data: np.ndarray) -> None:
    """Emit a C array definition with readable hex / decimal values."""
    flat     = data.flatten()
    n        = len(flat)
    per_line = 16 if "int8" in ctype else 8
    f.write(f"const {ctype} {name}[{n}] = {{\n")
    for i in range(0, n, per_line):
        chunk = flat[i : i + per_line]
        if ctype == "int8_t":
            row = ", ".join(f"0x{int(v) & 0xFF:02x}" for v in chunk)
        else:
            row = ", ".join(str(int(v)) for v in chunk)
        f.write(f"    {row},\n")
    f.write(f"}};\n\n")


# ---------------------------------------------------------------------------
# Fixed-point requantisation helpers
# ---------------------------------------------------------------------------

# Ops whose inputs include a per-channel weight tensor requiring per-channel
# effective requantisation: M_eff[c] = input_scale * weight_scale[c] / output_scale
_MAC_OPS: frozenset[str] = frozenset({"CONV_2D", "FULLY_CONNECTED", "DEPTHWISE_CONV_2D"})


def _get_scale(details: dict, idx: int, ch: int = 0) -> float:
    """Return the quantisation scale for tensor *idx*, channel *ch* (default 0)."""
    q      = details[idx].get("quantization_parameters", {})
    scales = list(q.get("scales", []))
    if not scales:
        return 1.0
    return float(scales[min(ch, len(scales) - 1)])


def _get_zp(details: dict, idx: int) -> int:
    """Return the zero-point for tensor *idx*."""
    q   = details[idx].get("quantization_parameters", {})
    zps = list(q.get("zero_points", []))
    return int(zps[0]) if zps else 0


def _quantize_multiplier(real_multiplier: float) -> tuple[int, int]:
    """Return TFLite-style ``(Q31 multiplier, signed binary exponent)``.

    The returned values encode

        real_multiplier ≈ (multiplier / 2^31) * 2^shift

    where ``multiplier`` is a positive int32 in [2^30, 2^31) and ``shift``
    is signed. A positive shift means a left shift; a negative shift means a
    right shift. The target kernel must use a TFLite/CMSIS-NN-compatible Q31
    requantization primitive (saturating rounding high-multiply followed by
    the signed power-of-two shift), rather than ``(acc * multiplier) >> shift``.

    Multipliers too small for TFLite's int32 requantization range are rounded
    to zero. Exponents above 30 are rejected because the corresponding int32
    left shift cannot be represented safely by the standard runtime helper.
    """
    if not math.isfinite(real_multiplier) or real_multiplier < 0.0:
        raise ValueError(
            f"quantized multiplier must be finite and non-negative; got {real_multiplier!r}"
        )
    if real_multiplier == 0.0:
        return 0, 0

    # frexp gives real_multiplier = significand * 2**shift with
    # significand in [0.5, 1.0). This is TFLite's shift convention.
    significand, shift = math.frexp(real_multiplier)

    # Convert the significand to Q31. Values are positive, so floor(x + 0.5)
    # matches C++ std::round instead of Python's ties-to-even round().
    q = int(math.floor(significand * (1 << 31) + 0.5))
    if q == (1 << 31):
        # Rounding reached 1.0. Represent it equivalently as
        # 0.5 * 2^(shift+1), keeping q representable as a signed int32.
        q //= 2
        shift += 1

    # Match TFLite's practical int32 requantization range.
    if shift < -31:
        return 0, 0
    if shift > 30:
        raise ValueError(
            f"quantized multiplier exponent {shift} is too large for int32 requantization"
        )

    assert (1 << 30) <= q < (1 << 31)
    return q, shift


# ---------------------------------------------------------------------------
# File emitters
# ---------------------------------------------------------------------------

def emit_weights(interp, out_dir: Path, constants: set[int]) -> None:
    """model_weights.c — one C array per constant tensor."""
    details = {t["index"]: t for t in interp.get_tensor_details()}
    path    = out_dir / "model_weights.c"
    written = 0

    with open(path, "w") as f:
        f.write(BANNER)
        f.write('#include "model_params.h"\n\n')

        for idx in sorted(constants):
            t     = details[idx]
            shape = list(t["shape"])
            if _nelems(shape) == 0:
                continue
            try:
                data = interp.get_tensor(idx)
            except Exception:
                continue

            ct = _ctype(data.dtype)
            f.write(f"/* t{idx}: {t['name']!r}  shape={shape} */\n")
            _write_c_array(f, ct, f"t{idx}_data", data)
            written += 1

    print(f"[ok] {path}  ({written} constant tensors)")


def emit_params_header(interp, out_dir: Path, constants: set[int]) -> None:
    """model_params.h — extern decls + per-tensor shape + zero-point macros.

    Float scales are deliberately NOT emitted here.  All requantisation
    multipliers (int32 fixed-point) are pre-computed per op and emitted
    in model_runner.c, keeping every generated C file entirely float-free.
    """
    details   = {t["index"]: t for t in interp.get_tensor_details()}
    model_in  = interp.get_input_details()
    model_out = interp.get_output_details()
    path      = out_dir / "model_params.h"

    with open(path, "w") as f:
        f.write(BANNER)
        f.write("#pragma once\n#include <stdint.h>\n\n")

        # Model-level I/O summary
        f.write("/* ---- model I/O ---- */\n")
        for d in model_in:
            f.write(f"#define MODEL_INPUT_IDX    {d['index']}\n")
            f.write(f"#define MODEL_INPUT_NELEMS {_nelems(d['shape'])}\n")
        for d in model_out:
            f.write(f"#define MODEL_OUTPUT_IDX    {d['index']}\n")
            f.write(f"#define MODEL_OUTPUT_NELEMS {_nelems(d['shape'])}\n")
        f.write("\n")

        # Per-tensor block
        for idx in sorted(details.keys()):
            t     = details[idx]
            shape = list(t["shape"])
            n     = _nelems(shape)
            if n == 0:
                continue

            ct  = _ctype(t["dtype"])
            zp  = _get_zp(details, idx)

            f.write(f"/* t{idx}: {t['name']!r}  shape={shape}  {ct} */\n")

            if idx in constants:
                f.write(f"extern const {ct} t{idx}_data[{n}];\n")

            shape_str = ", ".join(str(s) for s in shape)
            f.write(f"#define T{idx}_NDIM   {len(shape)}\n")
            f.write(f"#define T{idx}_SHAPE  {{{shape_str}}}\n")
            f.write(f"#define T{idx}_NELEMS {n}\n")
            f.write(f"#define T{idx}_ZP     {zp}\n")
            # Float scales omitted — requant multipliers are computed offline
            # and emitted as int32_t arrays in model_runner.c.
            f.write("\n")

    print(f"[ok] {path}")


def emit_runner(interp, out_dir: Path, constants: set[int]) -> None:
    """model_runner.c — static buffers + per-op int32 requant + kernel calls.

    Kernel argument conventions (no float anywhere):

      MAC ops (CONV_2D, FULLY_CONNECTED, DEPTHWISE_CONV_2D):
        input*, weights*, [bias*,] output*,
        input_zp, output_zp,
        op{n}_reqmult*,  op{n}_reqshift*,   ← per-channel int32 arrays
        out_dim0, out_dim1, ...

      ADD:
        in1*, in2*, output*,
        in1_zp, in2_zp, out_zp,
        in1_mult, in1_shift,               ← scalar int32 (M = in1_scale/out_scale)
        in2_mult, in2_shift,               ← scalar int32 (M = in2_scale/out_scale)
        out_dim0, out_dim1, ...

      All other ops:
        in0*, [in1*, ...] out*,
        in0_zp, out_zp,
        out_dim0, out_dim1, ...
    """
    ops           = interp._get_ops_details()  # noqa: SLF001
    details       = {t["index"]: t for t in interp.get_tensor_details()}
    model_inputs  = {d["index"] for d in interp.get_input_details()}
    model_outputs = {d["index"] for d in interp.get_output_details()}
    aliases       = _reshape_aliases(interp)

    aliased_outs = set(aliases.keys())
    act_tensors  = (
        {t["index"] for t in interp.get_tensor_details()}
        - constants - model_inputs - model_outputs - aliased_outs
    )

    def buf_expr(idx: int) -> str:
        r = _resolve(idx, aliases)
        if r in model_inputs:  return "input"
        if r in model_outputs: return "output"
        if r in constants:     return f"t{r}_data"
        return f"act_{r}"

    # ------------------------------------------------------------------
    # Pre-compute per-channel effective requant for every MAC op.
    # M_eff[c] = input_scale * weight_scale[c] / output_scale
    # ------------------------------------------------------------------
    mac_requant: dict[int, tuple[list[int], list[int]]] = {}
    for op in ops:
        if op["op_name"] not in _MAC_OPS:
            continue
        ins  = [x for x in op["inputs"]  if x >= 0]
        outs = [x for x in op["outputs"] if x >= 0]
        if len(ins) < 2 or not outs:
            continue
        in_scale  = _get_scale(details, ins[0])
        out_scale = _get_scale(details, outs[0])
        w_scales  = list(
            details[ins[1]].get("quantization_parameters", {}).get("scales", [1.0])
        )
        mults, shifts = [], []
        for ws in w_scales:
            m, s = _quantize_multiplier(in_scale * float(ws) / out_scale)
            mults.append(m)
            shifts.append(s)
        mac_requant[op["index"]] = (mults, shifts)

    path = out_dir / "model_runner.c"
    with open(path, "w") as f:
        f.write(BANNER)
        f.write('#include "model_params.h"\n')
        f.write('#include "kernels.h"\n')
        f.write('#include <stdint.h>\n')
        f.write('#include <string.h>\n\n')

        # ---- Activation buffers ------------------------------------------
        f.write("/* ---- activation buffers (static; avoids stack overflow) ---- */\n")
        for idx in sorted(act_tensors):
            t  = details[idx]
            sh = list(t["shape"])
            n  = _nelems(sh)
            if n == 0:
                continue
            ct = _ctype(t["dtype"])
            f.write(f"static {ct} act_{idx}[{n}]; /* {t['name']!r} {sh} */\n")
        f.write("\n")

        # ---- Per-op requant arrays ----------------------------------------
        if mac_requant:
            f.write("/* ---- per-op requantisation (int32, pre-computed offline — no FP at runtime) ----\n"
                    " *\n"
                    " * For each MAC op:  output_int8 ≈ SAT( (acc * reqmult[c]) >> reqshift[c] ) + out_zp\n"
                    " * where acc is the INT32 dot-product accumulator.\n"
                    " */\n")
            for op in ops:
                if op["index"] not in mac_requant:
                    continue
                op_name      = op["op_name"]
                n_idx        = op["index"]
                mults, shifts = mac_requant[n_idx]
                n_ch         = len(mults)
                per_line     = 8
                f.write(f"/* op {n_idx}: {op_name} — {n_ch} output channel(s) */\n")
                f.write(f"static const int32_t op{n_idx}_reqmult[{n_ch}] = {{\n")
                for i in range(0, n_ch, per_line):
                    row = ", ".join(str(v) for v in mults[i:i + per_line])
                    f.write(f"    {row},\n")
                f.write("};\n")
                f.write(f"static const int32_t op{n_idx}_reqshift[{n_ch}] = {{\n")
                for i in range(0, n_ch, per_line):
                    row = ", ".join(str(v) for v in shifts[i:i + per_line])
                    f.write(f"    {row},\n")
                f.write("};\n\n")

        # ---- model_run() -------------------------------------------------
        f.write("void model_run(const int8_t *input, int8_t *output) {\n")

        for op in ops:
            op_name = op["op_name"]
            op_idx  = op["index"]
            ins  = [x for x in op["inputs"]  if x >= 0]
            outs = [x for x in op["outputs"] if x >= 0]

            f.write(f"\n    /* op {op_idx}: {op_name}  in={ins}  out={outs} */\n")

            # RESHAPE: buffer alias — no data movement.
            if op_name == "RESHAPE":
                src = buf_expr(ins[0]) if ins else "?"
                dst = buf_expr(outs[0]) if outs else "?"
                f.write(f"    /* {src} reinterpreted as {dst} (RESHAPE, no copy) */\n")
                continue

            # DELEGATE: TFLite runtime-internal fusion marker — skip.
            if op_name == "DELEGATE":
                f.write(f"    /* DELEGATE (op {op_idx}): TFLite runtime fusion — skipped */\n")
                continue

            kernel = _op_to_kernel(op_name)
            args: list[str] = []

            if op_name in _MAC_OPS:
                # input, weights, [bias,] output, in_zp, out_zp,
                # reqmult*, reqshift*, shape...
                args += [buf_expr(x) for x in ins]   # input, weights, (bias)
                args += [buf_expr(x) for x in outs]  # output
                args += [f"T{ins[0]}_ZP", f"T{outs[0]}_ZP"]
                args += [f"op{op_idx}_reqmult", f"op{op_idx}_reqshift"]
                if outs and outs[0] in details:
                    args += [str(s) for s in details[outs[0]]["shape"]]

            elif op_name == "ADD":
                # in1, in2, output,
                # in1_zp, in2_zp, out_zp,
                # in1_mult, in1_shift, in2_mult, in2_shift, shape...
                if len(ins) >= 2 and outs:
                    m1, s1 = _quantize_multiplier(
                        _get_scale(details, ins[0]) / _get_scale(details, outs[0]))
                    m2, s2 = _quantize_multiplier(
                        _get_scale(details, ins[1]) / _get_scale(details, outs[0]))
                    args += [buf_expr(ins[0]), buf_expr(ins[1]), buf_expr(outs[0])]
                    args += [f"T{ins[0]}_ZP", f"T{ins[1]}_ZP", f"T{outs[0]}_ZP"]
                    args += [str(m1), str(s1), str(m2), str(s2)]
                    args += [str(s) for s in details[outs[0]]["shape"]]

            else:
                # Generic (PAD, POOL, TRANSPOSE, …):
                # all buf ptrs, in0_zp, out0_zp, shape
                args += [buf_expr(x) for x in ins]
                args += [buf_expr(x) for x in outs]
                if ins  and ins[0]  in details: args.append(f"T{ins[0]}_ZP")
                if outs and outs[0] in details: args.append(f"T{outs[0]}_ZP")
                if outs and outs[0] in details:
                    args += [str(s) for s in details[outs[0]]["shape"]]

            indent   = "    " + " " * (len(kernel) + 1)
            args_str = (",\n" + indent).join(args)
            f.write(f"    {kernel}({args_str});\n")

        f.write("}\n")

    print(f"[ok] {path}")


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

def main() -> None:
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument("--model", required=True,
                    help="path to the .tflite file (set via MODEL_OUT in the Makefile)")
    args = ap.parse_args()

    out_dir = Path(DEFAULT_OUT)
    out_dir.mkdir(parents=True, exist_ok=True)

    interp    = _load(args.model)
    constants = _constant_set(interp)

    ops       = interp._get_ops_details()  # noqa: SLF001
    n_tensors = len(interp.get_tensor_details())
    op_name_set = {op["op_name"] for op in ops}
    op_names    = sorted(op_name_set)
    skip        = {"RESHAPE", "DELEGATE"}
    mac_names   = sorted(op_name_set & _MAC_OPS)
    other       = sorted(n for n in op_name_set if n not in skip and n not in _MAC_OPS)
    print(f"[info] {n_tensors} tensors  |  {len(constants)} constants  |  {len(ops)} ops")
    print(f"[info] op types          : {op_names}")
    print(f"[info] MAC ops (per-ch requant)  : {mac_names}")
    print(f"[info] other ops (scalar / no requant): {other}")

    emit_weights(interp, out_dir, constants)
    emit_params_header(interp, out_dir, constants)
    emit_runner(interp, out_dir, constants)

    print(f"\n[ok] generated C in {out_dir}/")
    print("     Next: implement src/kernels/kernels.h, compile for RV64IMC, profile on Spike.")


if __name__ == "__main__":
    main()
