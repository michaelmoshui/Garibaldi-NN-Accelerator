#!/usr/bin/env python3
"""Generate the ImageNet photo demo data for the ResNet-18 LiteRT Micro workload.

Downloads 20 real ImageNet-1k photos (one per class) from
github.com/EliSchwartz/imagenet-sample-images, preprocesses them exactly as the
litert-community/resnet18 model card does (resize 256, centre-crop 224, ImageNet
mean/std, NCHW), quantizes them with the model's input scale / zero point and
runs them through LiteRT's BUILTIN_REF kernels to get reference int8 logits.

This script is demo-app-exclusive.  The shared TFLM runtime + model CC array
must be generated first (scripts/ml_workload/gen_tflm_workload.py / make model_workload).
Random golden test vectors for the test app live in gen_test_data.py.

Outputs (all under --out, default src/software/demo):
  images/*.JPEG                 the downloaded photos (cached between runs)
  demo_data/demo_images.{h,cc}  photo table: file name, true label, pixels, ref logits
  demo_data/image_NN.cc         int8 input tensor + reference logits per photo
  demo_data/imagenet_labels.cc  the 1000 ImageNet-1k class names

Usage:
    python scripts/ml_workload/gen_demo_data.py
    python scripts/ml_workload/gen_demo_data.py \
        --model path/to/model.tflite --out path/to/demo
"""

import argparse
import json
import shutil
import urllib.request
from pathlib import Path

import numpy as np
from PIL import Image

REPO_ROOT = Path(__file__).resolve().parent.parent.parent

DEFAULT_MODEL = REPO_ROOT / "src/software/model/resnet18_int8_channelwise.tflite"
DEFAULT_OUT = REPO_ROOT / "src/software/demo"

IMAGE_URL = "https://raw.githubusercontent.com/EliSchwartz/imagenet-sample-images/master/{}"
LABELS_REPO = "huggingface/label-files"
LABELS_FILE = "imagenet-1k-id2label.json"

# (ImageNet-1k class index, file in imagenet-sample-images)
DEMO_IMAGES = [
    (1,   "n01443537_goldfish.JPEG"),
    (22,  "n01614925_bald_eagle.JPEG"),
    (130, "n02007558_flamingo.JPEG"),
    (207, "n02099601_golden_retriever.JPEG"),
    (281, "n02123045_tabby.JPEG"),
    (291, "n02129165_lion.JPEG"),
    (323, "n02279972_monarch.JPEG"),
    (340, "n02391049_zebra.JPEG"),
    (388, "n02510455_giant_panda.JPEG"),
    (404, "n02690373_airliner.JPEG"),
    (417, "n02782093_balloon.JPEG"),
    (430, "n02802426_basketball.JPEG"),
    (468, "n02930766_cab.JPEG"),
    (779, "n04146614_school_bus.JPEG"),
    (817, "n04285008_sports_car.JPEG"),
    (849, "n04398044_teapot.JPEG"),
    (950, "n07747607_orange.JPEG"),
    (954, "n07753592_banana.JPEG"),
    (963, "n07873807_pizza.JPEG"),
    (980, "n09472597_volcano.JPEG"),
]

MEAN = np.array([0.485, 0.456, 0.406], dtype=np.float32)
STD = np.array([0.229, 0.224, 0.225], dtype=np.float32)


def download_images(images_dir: Path) -> None:
    images_dir.mkdir(parents=True, exist_ok=True)
    for _, name in DEMO_IMAGES:
        dst = images_dir / name
        if dst.is_file():
            continue
        print(f"  downloading {name}")
        with urllib.request.urlopen(IMAGE_URL.format(name)) as r, open(dst, "wb") as f:
            shutil.copyfileobj(r, f)


def load_labels() -> list:
    """Short (first-synonym) names of the 1000 ImageNet-1k classes, by index."""
    from huggingface_hub import hf_hub_download

    path = hf_hub_download(LABELS_REPO, LABELS_FILE, repo_type="dataset")
    with open(path, encoding="utf-8") as f:
        id2label = {int(k): v for k, v in json.load(f).items()}
    return [id2label[i].split(",")[0].strip() for i in range(len(id2label))]


def preprocess(path: Path) -> np.ndarray:
    """Float NCHW [1, 3, 224, 224] tensor, as in the litert-community/resnet18 model card."""
    img = Image.open(path).convert("RGB")
    w, h = img.size
    s = 256
    if w < h:
        img = img.resize((s, int(h * s / w)), Image.BILINEAR)
    else:
        img = img.resize((int(w * s / h), s), Image.BILINEAR)
    left = int(round((img.size[0] - 224) / 2.0))
    top = int(round((img.size[1] - 224) / 2.0))
    img = img.crop((left, top, left + 224, top + 224))

    x = np.asarray(img, dtype=np.float32) / 255.0
    x = (x - MEAN) / STD
    return np.ascontiguousarray(x.transpose(2, 0, 1)[None])


def quantize(x: np.ndarray, scale: float, zero_point: int) -> np.ndarray:
    q = np.round(x / scale) + zero_point
    return np.clip(q, -128, 127).astype(np.int8)


def c_array(values: np.ndarray, per_line: int = 24) -> str:
    flat = values.reshape(-1).tolist()
    lines = (", ".join(str(v) for v in flat[i:i + per_line])
             for i in range(0, len(flat), per_line))
    return "    " + ",\n    ".join(lines)


def c_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_sources(data_dir: Path, inputs: list, ref_logits: list, labels: list) -> None:
    shutil.rmtree(data_dir, ignore_errors=True)
    data_dir.mkdir(parents=True)
    n = len(DEMO_IMAGES)
    image_bytes = inputs[0].size
    num_classes = len(labels)
    banner = "// Generated by scripts/ml_workload/gen_demo_data.py. Do not edit.\n"

    externs = "\n".join(
        f"extern const int8_t g_demo_image_{i:02d}[kDemoImageBytes];\n"
        f"extern const int8_t g_demo_ref_logits_{i:02d}[kDemoNumClasses];"
        for i in range(n))
    (data_dir / "demo_images.h").write_text(f"""{banner}
#ifndef DEMO_DATA_DEMO_IMAGES_H_
#define DEMO_DATA_DEMO_IMAGES_H_

#include <cstdint>

constexpr int kDemoNumImages = {n};
constexpr int kDemoImageBytes = {image_bytes};
constexpr int kDemoNumClasses = {num_classes};

struct DemoImage {{
  const char* file;           // photo under src/software/demo/images/
  int label;                  // ground-truth ImageNet-1k class index
  const int8_t* pixels;       // quantized NCHW input tensor
  const int8_t* ref_logits;   // LiteRT BUILTIN_REF output for this input
}};

extern const DemoImage g_demo_images[kDemoNumImages];
extern const char* const g_imagenet_labels[kDemoNumClasses];

{externs}

#endif  // DEMO_DATA_DEMO_IMAGES_H_
""")

    rows = "\n".join(
        f"    {{{c_string(name)}, {label}, g_demo_image_{i:02d}, g_demo_ref_logits_{i:02d}}},"
        for i, (label, name) in enumerate(DEMO_IMAGES))
    (data_dir / "demo_images.cc").write_text(f"""{banner}
#include "demo_images.h"

const DemoImage g_demo_images[kDemoNumImages] = {{
{rows}
}};
""")

    for i, (x, y) in enumerate(zip(inputs, ref_logits)):
        (data_dir / f"image_{i:02d}.cc").write_text(f"""{banner}// {DEMO_IMAGES[i][1]}

#include "demo_images.h"

alignas(16) const int8_t g_demo_image_{i:02d}[kDemoImageBytes] = {{
{c_array(x)}
}};

const int8_t g_demo_ref_logits_{i:02d}[kDemoNumClasses] = {{
{c_array(y)}
}};
""")

    names = "\n".join(f"    {c_string(s)}," for s in labels)
    (data_dir / "imagenet_labels.cc").write_text(f"""{banner}
#include "demo_images.h"

const char* const g_imagenet_labels[kDemoNumClasses] = {{
{names}
}};
""")


def main() -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model", type=Path, default=DEFAULT_MODEL,
                    help=f"input .tflite (default: {DEFAULT_MODEL.relative_to(REPO_ROOT)})")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT,
                    help=f"demo directory (default: {DEFAULT_OUT.relative_to(REPO_ROOT)})")
    args = ap.parse_args()

    from ai_edge_litert.interpreter import Interpreter, OpResolverType

    out = args.out.resolve()
    images_dir = out / "images"

    print(f"[1/3] Fetching {len(DEMO_IMAGES)} ImageNet photos into {images_dir}")
    download_images(images_dir)
    labels = load_labels()

    print("[2/3] Preprocessing + running LiteRT reference kernels")
    interpreter = Interpreter(model_path=str(args.model.resolve()),
                              experimental_op_resolver_type=OpResolverType.BUILTIN_REF)
    interpreter.allocate_tensors()
    in_det = interpreter.get_input_details()[0]
    out_det = interpreter.get_output_details()[0]
    scale, zero_point = in_det["quantization"]

    inputs, ref_logits, correct = [], [], 0
    for label, name in DEMO_IMAGES:
        x = quantize(preprocess(images_dir / name), scale, zero_point)
        interpreter.set_tensor(in_det["index"], x)
        interpreter.invoke()
        y = interpreter.get_tensor(out_det["index"]).astype(np.int8).copy()
        pred = int(np.argmax(y))
        correct += pred == label
        print(f"  {name:36s} truth {labels[label]:20s} ref top-1 {labels[pred]}")
        inputs.append(x)
        ref_logits.append(y)
    print(f"  LiteRT reference top-1: {correct}/{len(DEMO_IMAGES)}")

    print(f"[3/3] Writing C++ arrays to {out / 'demo_data'}")
    write_sources(out / "demo_data", inputs, ref_logits, labels)
    print(f"[ok] Demo data written to {out}")


if __name__ == "__main__":
    main()
